-- PPT expansion, additive and idempotent. Apply ONLY to a staging clone first.
-- Source: Hindustan Pipes architecture design, slides 3-9.
CREATE TABLE IF NOT EXISTS production_jobs(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 product_id BIGINT NOT NULL,
 job_code TEXT NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 1000),
 step TEXT NOT NULL DEFAULT 'IRON_FABRICATION' CHECK(step IN ('IRON_FABRICATION','PRECAST_SETUP','DIE_FILLING','CAST_COMPLETE')),
 machine_label TEXT,
 die_label TEXT,
 operator_note TEXT,
 batch_id BIGINT,
 started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 step_changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,job_code),
 FOREIGN KEY(organization_id,product_id) REFERENCES pipe_products(organization_id,id),
 FOREIGN KEY(organization_id,batch_id) REFERENCES production_batches(organization_id,id)
);
CREATE TABLE IF NOT EXISTS production_job_history(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL REFERENCES production_jobs(id),
 from_step TEXT,
 to_step TEXT NOT NULL,
 note TEXT,
 changed_by BIGINT REFERENCES app_users(id),
 changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS warehouse_bundles(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 lot_id BIGINT NOT NULL REFERENCES warehouse_lots(id),
 bundle_code TEXT NOT NULL,
 bundle_index INTEGER NOT NULL CHECK(bundle_index>0),
 pipe_quantity INTEGER NOT NULL CHECK(pipe_quantity>0),
 is_partial BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,bundle_code),
 UNIQUE(lot_id,bundle_index)
);
CREATE TABLE IF NOT EXISTS finished_goods_catalog(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 sku TEXT NOT NULL,
 name TEXT NOT NULL,
 category TEXT NOT NULL CHECK(category IN ('PAVING_BLOCK','JOINTER')),
 unit TEXT NOT NULL DEFAULT 'piece',
 quantity_on_hand NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(quantity_on_hand>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,sku)
);
CREATE INDEX IF NOT EXISTS ix_production_jobs_step ON production_jobs(organization_id,step,started_at DESC);
CREATE INDEX IF NOT EXISTS ix_bundles_lot ON warehouse_bundles(organization_id,lot_id);
