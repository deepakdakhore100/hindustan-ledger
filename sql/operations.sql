-- Hindustan Pipes + BBQ Pav Bhaji: first-stage operations tables.
-- Run against Neon database: hindustan_ledger. Idempotent; does not drop existing tables.
-- Manufacturing recipes and restaurant taxes must be verified with the client.

CREATE TABLE IF NOT EXISTS raw_materials (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL REFERENCES organizations(id),
 code TEXT NOT NULL,
 name TEXT NOT NULL,
 unit TEXT NOT NULL CHECK (unit IN ('kg','bag','bowl','litre','tonne','piece')),
 quantity_on_hand NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
 reorder_level NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
 unit_cost NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE (organization_id, code), UNIQUE (organization_id,id)
);

CREATE TABLE IF NOT EXISTS raw_material_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL,
 raw_material_id BIGINT NOT NULL,
 quantity_delta NUMERIC(14,3) NOT NULL CHECK (quantity_delta <> 0),
 reason TEXT NOT NULL CHECK (reason IN ('PURCHASE','ADJUSTMENT','PRODUCTION')),
 reference TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(organization_id,raw_material_id) REFERENCES raw_materials(organization_id,id)
);

CREATE TABLE IF NOT EXISTS pipe_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL REFERENCES organizations(id),
 diameter_mm INT NOT NULL CHECK(diameter_mm IN (300,450,600)),
 end_type TEXT NOT NULL CHECK(end_type IN ('SOCKET','PLAIN')),
 unit_price NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(unit_price >= 0),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(organization_id,diameter_mm,end_type),UNIQUE(organization_id,id)
);

CREATE TABLE IF NOT EXISTS pipe_recipes (
 organization_id INT NOT NULL,
 product_id BIGINT NOT NULL,
 raw_material_id BIGINT NOT NULL,
 qty_per_pipe NUMERIC(14,3) NOT NULL CHECK(qty_per_pipe > 0),
 PRIMARY KEY(organization_id,product_id,raw_material_id),
 FOREIGN KEY(organization_id,product_id) REFERENCES pipe_products(organization_id,id),
 FOREIGN KEY(organization_id,raw_material_id) REFERENCES raw_materials(organization_id,id)
);

CREATE TABLE IF NOT EXISTS production_batches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL,
 product_id BIGINT NOT NULL,
 batch_code TEXT NOT NULL,
 quantity INT NOT NULL CHECK(quantity > 0),
 stage TEXT NOT NULL DEFAULT 'DRY_CURING'
   CHECK(stage IN ('DRY_CURING','WATER_CURING','READY','WAREHOUSE')),
 started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 stage_changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 notes TEXT,
 UNIQUE(organization_id,batch_code),UNIQUE(organization_id,id),
 FOREIGN KEY(organization_id,product_id) REFERENCES pipe_products(organization_id,id)
);

CREATE TABLE IF NOT EXISTS batch_material_usage (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL,
 batch_id BIGINT NOT NULL,
 raw_material_id BIGINT NOT NULL,
 quantity_used NUMERIC(14,3) NOT NULL CHECK(quantity_used > 0),
 FOREIGN KEY(organization_id,batch_id) REFERENCES production_batches(organization_id,id),
 FOREIGN KEY(organization_id,raw_material_id) REFERENCES raw_materials(organization_id,id)
);

CREATE TABLE IF NOT EXISTS batch_stage_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL,
 batch_id BIGINT NOT NULL,
 from_stage TEXT,
 to_stage TEXT NOT NULL,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(organization_id,batch_id) REFERENCES production_batches(organization_id,id)
);

CREATE TABLE IF NOT EXISTS warehouse_zones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL REFERENCES organizations(id),
 code TEXT NOT NULL,
 name TEXT NOT NULL,
 UNIQUE(organization_id,code),UNIQUE(organization_id,id)
);

CREATE TABLE IF NOT EXISTS warehouse_lots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL,
 batch_id BIGINT NOT NULL,
 zone_id BIGINT,
 lot_code TEXT NOT NULL,
 quantity INT NOT NULL CHECK(quantity > 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,lot_code),
 FOREIGN KEY(organization_id,batch_id) REFERENCES production_batches(organization_id,id),
 FOREIGN KEY(organization_id,zone_id) REFERENCES warehouse_zones(organization_id,id)
);

CREATE TABLE IF NOT EXISTS pos_menu_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL REFERENCES organizations(id),
 name TEXT NOT NULL,
 category TEXT NOT NULL DEFAULT 'Main',
 price NUMERIC(14,2) NOT NULL CHECK(price >= 0),
 available BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,id)
);

CREATE TABLE IF NOT EXISTS pos_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL REFERENCES organizations(id),
 order_no TEXT NOT NULL,
 channel TEXT NOT NULL CHECK(channel IN ('DINE_IN','TAKEAWAY','ONLINE_MANUAL')),
 table_label TEXT,
 status TEXT NOT NULL DEFAULT 'NEW' CHECK(status IN ('NEW','PREPARING','READY','COMPLETED','CANCELLED')),
 subtotal NUMERIC(14,2) NOT NULL CHECK(subtotal >= 0),
 tax_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(tax_amount >= 0),
 total_amount NUMERIC(14,2) NOT NULL CHECK(total_amount >= 0),
 payment_method TEXT CHECK(payment_method IN ('CASH','UPI','CARD','UNPAID')),
 notes TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,order_no),UNIQUE(organization_id,id)
);

CREATE TABLE IF NOT EXISTS pos_order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INT NOT NULL,
 order_id BIGINT NOT NULL,
 menu_item_id BIGINT NOT NULL,
 name_snapshot TEXT NOT NULL,
 quantity INT NOT NULL CHECK(quantity>0),
 unit_price NUMERIC(14,2) NOT NULL CHECK(unit_price>=0),
 line_total NUMERIC(14,2) NOT NULL CHECK(line_total>=0),
 FOREIGN KEY(organization_id,order_id) REFERENCES pos_orders(organization_id,id),
 FOREIGN KEY(organization_id,menu_item_id) REFERENCES pos_menu_items(organization_id,id)
);

CREATE INDEX IF NOT EXISTS ix_material_movements_recent ON raw_material_movements(organization_id,created_at DESC);

CREATE INDEX IF NOT EXISTS ix_batches_stage ON production_batches(organization_id,stage,started_at DESC);

CREATE INDEX IF NOT EXISTS ix_orders_kitchen ON pos_orders(organization_id,status,created_at DESC);

INSERT INTO pipe_products(organization_id,diameter_mm,end_type)
 SELECT o.id,d.diameter_mm,e.end_type FROM organizations o
 CROSS JOIN (VALUES(300),(450),(600)) AS d(diameter_mm)
 CROSS JOIN (VALUES('PLAIN'),('SOCKET')) AS e(end_type)
 WHERE o.name='Hindustan Pipes'
 ON CONFLICT(organization_id,diameter_mm,end_type) DO NOTHING;

INSERT INTO warehouse_zones(organization_id,code,name)
 SELECT o.id,z.code,z.name FROM organizations o
 CROSS JOIN (VALUES('A','Zone A'),('B','Zone B'),('C','Zone C')) AS z(code,name)
 WHERE o.name='Hindustan Pipes'
 ON CONFLICT(organization_id,code) DO NOTHING;

INSERT INTO raw_materials(organization_id,code,name,unit)
 SELECT o.id,m.code,m.name,m.unit FROM organizations o
 CROSS JOIN (VALUES
 ('CEMENT','Cement','bag'),('SAND','Sand','bowl'),('AGGREGATE','Aggregate / Gitti','bowl'),
 ('DUST','Stone Dust','bowl'),('IRON-8','Iron 8 Gauge','kg'),('IRON-10','Iron 10 Gauge','kg'),
 ('IRON-12','Iron 12 Gauge','kg'),('IRON-14','Iron 14 Gauge','kg'),('DIE-OIL','Die Oil','litre')
 ) AS m(code,name,unit)
 WHERE o.name='Hindustan Pipes'
 ON CONFLICT(organization_id,code) DO NOTHING;
