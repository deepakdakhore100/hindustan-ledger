-- Hindustan Pipes inventory/production + BBQ Pav Bhaji POS.
-- Run against the separate hindustan_ledger database in Neon.
-- Idempotent schema and catalog seeds. No sample financial transactions.

CREATE TABLE IF NOT EXISTS public.materials (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id),
 name TEXT NOT NULL,
 unit TEXT NOT NULL CHECK (length(trim(unit))>0),
 stock_qty NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (stock_qty>=0),
 reorder_level NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (reorder_level>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,name),
 UNIQUE(organization_id,id)
);

CREATE TABLE IF NOT EXISTS public.pipe_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id),
 sku TEXT NOT NULL,
 name TEXT NOT NULL,
 category TEXT NOT NULL CHECK (category IN ('PIPE','PAVING_BLOCK','JOINTER')),
 diameter_mm INTEGER,
 joint_type TEXT CHECK (joint_type IN ('SOCKET','PLAIN')),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(organization_id,sku),
 UNIQUE(organization_id,id),
 CONSTRAINT pipe_attributes CHECK (category <> 'PIPE' OR (diameter_mm IN (300,450,600) AND joint_type IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.production_batches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id),
 product_id BIGINT NOT NULL,
 batch_code TEXT NOT NULL,
 quantity INTEGER NOT NULL CHECK (quantity>0),
 stage TEXT NOT NULL DEFAULT 'PRODUCTION' CHECK(stage IN ('PRODUCTION','DRY_CURING','WATER_CURING','WAREHOUSE')),
 warehouse_zone TEXT,
 remarks TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 stage_updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,batch_code),
 UNIQUE(organization_id,id),
 FOREIGN KEY(organization_id,product_id) REFERENCES public.pipe_products(organization_id,id)
);

CREATE TABLE IF NOT EXISTS public.material_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id),
 material_id BIGINT NOT NULL,
 batch_id BIGINT,
 quantity_delta NUMERIC(14,3) NOT NULL CHECK(quantity_delta<>0),
 reason TEXT NOT NULL CHECK(reason IN ('PURCHASE','ADJUSTMENT','CONSUMPTION')),
 note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(organization_id,material_id) REFERENCES public.materials(organization_id,id),
 FOREIGN KEY(organization_id,batch_id) REFERENCES public.production_batches(organization_id,id)
);

CREATE TABLE IF NOT EXISTS public.pos_menu_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id),
 name TEXT NOT NULL,
 price NUMERIC(12,2) NOT NULL CHECK(price>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,name),
 UNIQUE(organization_id,id)
);

CREATE TABLE IF NOT EXISTS public.pos_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id),
 order_number TEXT NOT NULL,
 source TEXT NOT NULL CHECK(source IN ('DINE_IN','TAKEAWAY','ZOMATO_MANUAL')),
 table_label TEXT,
 external_reference TEXT,
 status TEXT NOT NULL DEFAULT 'NEW' CHECK(status IN ('NEW','PREPARING','READY','SERVED','CANCELLED')),
 total_amount NUMERIC(14,2) NOT NULL CHECK(total_amount>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,order_number),
 UNIQUE(organization_id,id)
);

CREATE TABLE IF NOT EXISTS public.pos_order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id),
 order_id BIGINT NOT NULL,
 menu_item_id BIGINT NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity>0),
 unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>0),
 line_total NUMERIC(14,2) NOT NULL CHECK(line_total>=0),
 FOREIGN KEY(organization_id,order_id) REFERENCES public.pos_orders(organization_id,id),
 FOREIGN KEY(organization_id,menu_item_id) REFERENCES public.pos_menu_items(organization_id,id)
);

CREATE INDEX IF NOT EXISTS idx_material_movements_org_time ON public.material_movements(organization_id,created_at DESC);

CREATE INDEX IF NOT EXISTS idx_batches_org_stage ON public.production_batches(organization_id,stage);

CREATE INDEX IF NOT EXISTS idx_pos_orders_org_time ON public.pos_orders(organization_id,created_at DESC);

INSERT INTO public.materials(organization_id,name,unit)
 SELECT o.id,v.name,v.unit FROM public.organizations o
 CROSS JOIN (VALUES ('Cement','BAG'),('Iron bars','KG'),('Sand','BOWL'),('Dust','BOWL'),('Aggregate (Gitti)','BOWL'),('Mould oil','L')) v(name,unit)
 WHERE o.name='Hindustan Pipes' ON CONFLICT(organization_id,name) DO NOTHING;

INSERT INTO public.pipe_products(organization_id,sku,name,category,diameter_mm,joint_type)
 SELECT o.id,'PIPE-'||v.mm||'-'||v.joint, v.mm||'mm '||CASE WHEN v.joint='SOCKET' THEN 'Socket' ELSE 'Plain' END||' Pipe', 'PIPE',v.mm,v.joint
 FROM public.organizations o CROSS JOIN (VALUES(300,'SOCKET'),(300,'PLAIN'),(450,'SOCKET'),(450,'PLAIN'),(600,'SOCKET'),(600,'PLAIN'))v(mm,joint)
 WHERE o.name='Hindustan Pipes' ON CONFLICT(organization_id,sku) DO NOTHING;
